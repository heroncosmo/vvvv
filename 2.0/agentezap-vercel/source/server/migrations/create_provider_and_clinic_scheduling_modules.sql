CREATE TABLE IF NOT EXISTS provider_appointments (
  id varchar PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id varchar NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  conversation_id varchar,
  client_name varchar(255) NOT NULL,
  client_phone varchar(50) NOT NULL,
  client_email varchar(255),
  service_name varchar(255),
  appointment_date varchar(20) NOT NULL,
  start_time varchar(10) NOT NULL,
  end_time varchar(10) NOT NULL,
  duration_minutes integer DEFAULT 60,
  service_id varchar REFERENCES provider_services(id) ON DELETE SET NULL,
  professional_id varchar REFERENCES provider_professionals(id) ON DELETE SET NULL,
  professional_name varchar(255),
  location varchar(500),
  location_type varchar(50) DEFAULT 'presencial',
  meeting_link varchar(500),
  status varchar(50) DEFAULT 'pending',
  confirmed_by_client boolean DEFAULT false,
  confirmed_by_business boolean DEFAULT false,
  confirmed_at timestamp,
  cancelled_at timestamp,
  cancelled_by varchar(50),
  cancellation_reason text,
  reminder_sent boolean DEFAULT false,
  reminder_sent_at timestamp,
  reminder_times_sent jsonb DEFAULT '[]'::jsonb,
  google_event_id varchar(255),
  google_calendar_synced boolean DEFAULT false,
  client_notes text,
  internal_notes text,
  custom_message text,
  use_custom_message boolean DEFAULT false,
  custom_message_sent_at timestamp,
  created_by_ai boolean DEFAULT false,
  ai_confirmation_pending boolean DEFAULT false,
  ai_conversation_context jsonb,
  created_at timestamp DEFAULT now(),
  updated_at timestamp DEFAULT now()
);

