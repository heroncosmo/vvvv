CREATE TABLE IF NOT EXISTS provider_config (
  id varchar PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id varchar NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  is_active boolean DEFAULT false,
  send_to_ai boolean DEFAULT true,
  salon_name varchar(255),
  salon_type varchar(50) DEFAULT 'provider',
  phone varchar(50),
  address varchar(500),
  opening_hours jsonb DEFAULT '{}'::jsonb,
  slot_duration integer DEFAULT 30,
  buffer_between integer DEFAULT 10,
  max_advance_days integer DEFAULT 30,
  min_notice_hours integer DEFAULT 2,
  min_notice_minutes integer DEFAULT 0,
  allow_cancellation boolean DEFAULT true,
  cancellation_notice_hours integer DEFAULT 4,
  use_services boolean DEFAULT true,
  use_professionals boolean DEFAULT true,
  allow_multiple_services boolean DEFAULT false,
  service_name varchar(255),
  welcome_message text,
  booking_confirmation_message text,
  reminder_message text,
  cancellation_message text,
  closed_message text,
  humanize_responses boolean DEFAULT true,
  use_customer_name boolean DEFAULT true,
  response_variation boolean DEFAULT true,
  response_delay_min integer DEFAULT 1000,
  response_delay_max integer DEFAULT 3000,
  ai_instructions text,
  display_instructions text,
  google_calendar_enabled boolean DEFAULT false,
  google_calendar_id varchar(255),
  created_at timestamp DEFAULT now(),
  updated_at timestamp DEFAULT now()
);

